#!/bin/bash
cat << 'EOF'
╔════════════════════════════════════════════════════════════════════╗
║                    KITTY KEYBOARD SHORTCUTS                        ║
╚════════════════════════════════════════════════════════════════════╝

TABS
────────────────────────────────────────────────────────────────────
  cmd+t              New tab (current directory)
  cmd+w              Close tab
  cmd+1-5            Switch to tab 1-5
  cmd+shift+]        Next tab
  cmd+shift+[        Previous tab

SPLITS
────────────────────────────────────────────────────────────────────
  cmd+enter          Split vertically (right)
  cmd+shift+w        Close window

Move splits:
  cmd+left           Move window left
  cmd+right          Move window right
  cmd+up             Move window up
  cmd+down           Move window down

Navigate splits:
  cmd+shift+h        Focus window left
  cmd+shift+l        Focus window right
  cmd+shift+k        Focus window up
  cmd+shift+j        Focus window down

FONT
────────────────────────────────────────────────────────────────────
  cmd+equal          Increase font size
  cmd+minus          Decrease font size
  cmd+0              Reset font size

OTHER
────────────────────────────────────────────────────────────────────
  cmd+?              Show this help (press q to exit)

EOF
